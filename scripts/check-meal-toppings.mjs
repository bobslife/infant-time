import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
const storage = new Map();
const originalWindow = globalThis.window;
globalThis.window = { localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) } };
try {
  const catalog = await server.ssrLoadModule('/src/features/meals/toppings.ts');
  const local = await server.ssrLoadModule('/src/lib/storage/localRepository.ts');
  const remote = await server.ssrLoadModule('/src/lib/storage/supabaseRepository.ts');
  const { buildSummary } = await server.ssrLoadModule('/src/features/events/useEvents.ts');
  const { SummaryCards } = await server.ssrLoadModule('/src/components/SummaryCards.tsx');
  const { EventList } = await server.ssrLoadModule('/src/components/EventList.tsx');
  const { MealToppingChips } = await server.ssrLoadModule('/src/components/MealToppingChips.tsx');
  assert.equal(catalog.getStageToppings('early').length, 8);
  assert.equal(catalog.getStageToppings('middle').length, 12);
  assert.equal(catalog.getStageToppings('late').length, 16);
  for (const topping of catalog.mealToppings) assert.ok(existsSync(`public/icons/toppings/${topping.id}.svg`));
  catalog.rememberMealStage('baby-a', 'middle');
  assert.equal(catalog.getRememberedMealStage('baby-a', []), 'middle');
  assert.equal(catalog.getRememberedMealStage('baby-a', [{ babyId:'baby-a', mealStage:'late', occurredAt:'2026-09-20T10:00:00' }]), 'late');
  assert.equal(catalog.getRememberedMealStage('baby-b', []), 'early');
  assert.equal(catalog.getRememberedMealStage('baby-b', [{ babyId:'baby-b', mealStage:'late', occurredAt:'2026-09-20T10:00:00' }]), 'late');
  assert.equal(catalog.createCustomToppingId('  비트  '), 'custom:비트');
  assert.equal(catalog.createCustomToppingId('쌀'), 'rice');
  assert.equal(catalog.createCustomToppingId('rice'), 'custom:rice');
  assert.throws(() => catalog.createCustomToppingId('   '));
  assert.throws(() => catalog.createCustomToppingId('가'.repeat(31)));
  assert.equal(catalog.getMealCombination(['rice', 'custom:비트']), '쌀 · 비트');
  const customChip = renderToStaticMarkup(React.createElement(MealToppingChips, { ids:['custom:비트'] }));
  assert.ok(customChip.includes('비트'));
  assert.ok(!customChip.includes('custom:'));
  assert.ok(!customChip.includes('<img'));
  const compactChips = renderToStaticMarkup(React.createElement(MealToppingChips, { ids:['rice','beef','zucchini','potato','carrot'], maxVisible:3 }));
  assert.ok(compactChips.includes('쌀'));
  assert.ok(compactChips.includes('소고기'));
  assert.ok(compactChips.includes('애호박'));
  assert.ok(compactChips.includes('+2개'));
  assert.ok(!compactChips.includes('감자'));
  assert.ok(!compactChips.includes('당근'));
  const input = { babyId:'baby-a', eventType:'meal', occurredAt:'2026-09-20T12:00:00', mealName:'쌀 · 소고기', mealAmountG:80, mealStage:'early', mealToppings:['rice','beef'] };
  const created = await local.createLocalEvent(input);
  assert.deepEqual(created.mealToppings, ['rice','beef']);
  const updated = await local.updateLocalEvent({ ...input, id:created.id, mealStage:'middle', mealToppings:['oat','tofu'], mealName:'오트밀 두부죽' });
  assert.equal(updated.mealStage, 'middle');
  assert.deepEqual((await local.listLocalEvents('baby-a'))[0].mealToppings, ['oat','tofu']);
  await local.updateLocalEvent({ ...input, id:created.id, mealToppings:[] });
  assert.deepEqual((await local.listLocalEvents('baby-a'))[0].mealToppings, []);
  let written;
  const row = payload => ({ id:'remote', created_at:'2026-09-20T12:00:00', ...payload });
  const client = { from() { return { insert(payload) { written = payload; return this; }, update(payload) { written = payload; return this; }, eq() { return this; }, select() { return this; }, async single() { return { data:row(written), error:null }; } }; } };
  const stored = await remote.createSupabaseEvent(client, 'test-user', input);
  assert.deepEqual(written.meal_toppings, ['rice','beef']);
  assert.equal(written.meal_stage, 'early');
  assert.deepEqual(stored.mealToppings, ['rice','beef']);
  const customLocal = await local.createLocalEvent({ ...input, mealToppings:['rice','custom:비트'] });
  assert.deepEqual((await local.listLocalEvents('baby-a')).find(item => item.id === customLocal.id).mealToppings, ['rice','custom:비트']);
  const customRemote = await remote.createSupabaseEvent(client, 'test-user', { ...input, mealToppings:['rice','custom:비트'] });
  assert.deepEqual(customRemote.mealToppings, ['rice','custom:비트']);
  const changed = await remote.updateSupabaseEvent(client, { ...input, id:'remote', mealStage:'late', mealToppings:[] });
  assert.deepEqual(changed.mealToppings, []);
  assert.equal(changed.mealStage, 'late');
  const noop = () => {};
  const record = renderToStaticMarkup(React.createElement(EventList, { events:[created], onDelete:noop, onEdit:noop }));
  for (const text of ['80g','/icons/toppings/rice.svg','/icons/toppings/beef.svg','event-row-meal']) assert.ok(record.includes(text), text);
  assert.ok(record.includes('>이유식<'));
  assert.ok(!record.includes('이유식 (쌀 · 소고기)'));
  assert.ok(record.includes('event-meal-amount'));
  assert.ok(!record.includes('초기 이유식'));
  assert.ok(!record.includes('<small>쌀 · 소고기</small>'));
  const namedRecord = renderToStaticMarkup(React.createElement(EventList, { events:[updated], onDelete:noop, onEdit:noop }));
  assert.ok(namedRecord.includes('이유식 (오트밀 두부죽)'));
  assert.ok(namedRecord.indexOf('이유식 (오트밀 두부죽)') < namedRecord.indexOf('오트밀'));
  const legacy = renderToStaticMarkup(React.createElement(EventList, { events:[{ ...created, mealToppings:undefined, mealStage:null, mealName:'쌀미음' }], onDelete:noop, onEdit:noop }));
  assert.ok(legacy.includes('이유식 (쌀미음)'));
  assert.ok(renderToStaticMarkup(React.createElement(MealToppingChips, {ids:['future-ingredient']})).includes('future-ingredient'));
  const feeds = [{ ...created, eventType:'feed', amountMl:120, occurredAt:'2026-09-20T23:58:00' }, { ...created, occurredAt:'2026-09-20T23:57:00' }, { ...created, id:'future', occurredAt:'2026-09-22T12:00:00' }];
  const before = buildSummary(feeds, new Date('2026-09-20T23:59:00'));
  const after = buildSummary(feeds, new Date('2026-09-21T00:00:00'));
  assert.equal(before.todayFeedCount, 1); assert.equal(before.todayMealCount, 1);
  assert.equal(after.todayFeedCount, 0); assert.equal(after.todayMealCount, 0);
  const props = { baby:{id:'baby-a',name:'테스트',birthDate:'2026-01-01',gender:'girl'}, events:feeds, summary:before, feedIntervalMinutes:180, onQuickAdd:noop, onWakeSleep:noop, onEndPlay:noop, onFeedIntervalChange:noop };
  const preview = renderToStaticMarkup(React.createElement(SummaryCards, { ...props, previewEmptyIntake:true }));
  assert.ok(preview.includes('오늘 이유식 기록이 없어요'));
  assert.ok(preview.includes('오늘 분유·모유 수유 기록이 없어요'));
  assert.ok(!preview.includes('다음 수유 예측'));
  const naturalEmpty = renderToStaticMarkup(React.createElement(SummaryCards, {...props, summary:after}));
  assert.ok(naturalEmpty.includes('오늘 이유식 기록이 없어요'));
  assert.ok(naturalEmpty.includes('오늘 분유·모유 수유 기록이 없어요'));
  const normal = renderToStaticMarkup(React.createElement(SummaryCards, props));
  assert.ok(normal.includes('마지막 이유식'));
  assert.ok(normal.includes('다음 수유 예측'));
  assert.equal(before.todayMealCount, 1); // Preview did not mutate the real summary.
  console.log('PASS: stages, latest-event preference, icons, compact toppings, meal title, local create/update, remote serialization, legacy display, midnight reset, preview and restore');
} finally { globalThis.window = originalWindow; await server.close(); }
